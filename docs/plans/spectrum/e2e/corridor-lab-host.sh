#!/usr/bin/env bash
# Layer A — host corridor lab film (notify plane).
#
# Starts hash-market-server with host lab config, runs corridor-lab-smoke.sh, stops.
# Does NOT claim mainnet BTC/ZEC. Design freezes: D1–D7.
#
# Env:
#   HASH_MARKET_BIN   — path to hash-market-server (optional)
#   HASH_MARKET_URL   — override (default http://127.0.0.1:19090)
#   SKIP_BUILD=1      — do not cargo build if binary missing
#   KEEP_SERVER=1     — leave server running after smoke
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
HM_CRATE="$REPO_ROOT/crates/terp-rs/tools/hash-market"
HM_WS="$REPO_ROOT/crates/terp-rs"
DEFAULT_BIN="$HM_WS/target/release/hash-market-server"
BIN="${HASH_MARKET_BIN:-$DEFAULT_BIN}"
BASE="${HASH_MARKET_URL:-http://127.0.0.1:19090}"
PORT="${BASE##*:}"
PORT="${PORT%%/*}"

LAB_RUN_DIR="${CORRIDOR_LAB_DIR:-$(mktemp -d -t corridor-lab-XXXXXX)}"
mkdir -p "$LAB_RUN_DIR/data"
CONFIG="$LAB_RUN_DIR/config.toml"

# Host-writable config (absolute data_dir for this run).
cat >"$CONFIG" <<EOF
# Generated by corridor-lab-host.sh — lab only
bind = "127.0.0.1:${PORT}"
chain_id = "corridor-lab-1"
data_dir = "$LAB_RUN_DIR/data"
ve_enabled = false
cors_allow_origin = "*"
EOF

if [ ! -x "$BIN" ]; then
  if [ "${SKIP_BUILD:-0}" = "1" ]; then
    echo "ERROR: hash-market-server not found at $BIN (SKIP_BUILD=1)" >&2
    exit 1
  fi
  echo "== build hash-market-server (features=server) =="
  (cd "$HM_CRATE" && cargo build --release --bin hash-market-server --features server)
  BIN="$DEFAULT_BIN"
fi

if [ ! -x "$BIN" ]; then
  echo "ERROR: binary still missing: $BIN" >&2
  exit 1
fi

# Free port if a previous lab server is stuck (only if health looks like our lab).
if curl -sf "$BASE/health" >/dev/null 2>&1; then
  echo "== existing server at $BASE — reusing for smoke =="
  export HASH_MARKET_URL="$BASE"
  bash "$SCRIPT_DIR/corridor-lab-smoke.sh"
  exit 0
fi

echo "== start hash-market-server =="
echo "  bin=$BIN"
echo "  config=$CONFIG"
echo "  url=$BASE"
"$BIN" -c "$CONFIG" >"$LAB_RUN_DIR/server.log" 2>&1 &
SPID=$!
cleanup() {
  if [ "${KEEP_SERVER:-0}" != "1" ]; then
    kill "$SPID" 2>/dev/null || true
    wait "$SPID" 2>/dev/null || true
  else
    echo "KEEP_SERVER=1 pid=$SPID log=$LAB_RUN_DIR/server.log"
  fi
}
trap cleanup EXIT

for i in $(seq 1 50); do
  if curl -sf "$BASE/health" >/dev/null 2>&1; then
    break
  fi
  if ! kill -0 "$SPID" 2>/dev/null; then
    echo "ERROR: server exited early; log:" >&2
    cat "$LAB_RUN_DIR/server.log" >&2 || true
    exit 1
  fi
  sleep 0.1
done

if ! curl -sf "$BASE/health" >/dev/null 2>&1; then
  echo "ERROR: server did not become healthy at $BASE" >&2
  cat "$LAB_RUN_DIR/server.log" >&2 || true
  exit 1
fi

export HASH_MARKET_URL="$BASE"
bash "$SCRIPT_DIR/corridor-lab-smoke.sh"
echo
echo "OK Layer A host notify plane (lab dir $LAB_RUN_DIR)"
